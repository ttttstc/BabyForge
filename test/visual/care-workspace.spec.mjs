test('today is view-only and records stay in the record center', async ({ page }) => {
  await createBaby(page)
  await expect(page.getByText('喂养 · 今天', { exact: true })).toBeVisible()
  await expect(page.getByText('睡眠 · 今天', { exact: true })).toBeVisible()
  await expect(page.getByText('尿布 · 今天', { exact: true })).toBeVisible()
  await expect(page.getByText('用药 · 今天', { exact: true })).toBeVisible()
  await expect(page.getByLabel('发生时间')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /去记录中心录入/ })).toBeVisible()
  await page.getByRole('button', { name: '喂养 · 今天' }).click()
  await expect(page).toHaveURL(/#\/records\?type=feeding&return=today$/)
  await page.getByTestId('record-entry-feeding').getByRole('button', { name: '配方奶' }).click()
  await page.getByLabel('实际喝下奶量').fill('60')
  await page.getByRole('button', { name: '保存事实' }).click()
  await expect(page).toHaveURL(/#\/today$/)
  await page.getByRole('button', { name: '喂养 · 今天' }).click()
  await expect(page).toHaveURL(/#\/records\?type=feeding&return=today$/)
  await expect(page.getByText('配方奶 60 mL', { exact: true }).first()).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: '作废 配方奶 60 mL' }).click()
  await expect(page.getByText('配方奶 60 mL', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '就医摘要', exact: true }).click()
  await expect(page).toHaveURL(/#\/doctor-summary$/)
})
